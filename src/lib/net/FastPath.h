#pragma once

#include "arch/IArchNetwork.h"
#include "net/NetworkAddress.h"

#include <array>
#include <atomic>
#include <cstddef>
#include <cstdint>
#include <map>
#include <mutex>

namespace inputleap {

class EventTarget;
class IEventQueue;
class Thread;

//! Mouse motion delivered over the UDP fast path
struct FastPathMotionInfo {
    std::int32_t x = 0;
    std::int32_t y = 0;
    bool relative = false;
};

/*!
Encrypted, unreliable datagram channel for mouse motion.

TCP provides ordering and reliability, but on lossy links a single lost
segment blocks all subsequent input (head-of-line blocking). Motion is
different from buttons and keys: absolute positions are disposable and
the newest one wins. Sending them over UDP lets the receiver apply the
latest position immediately instead of waiting for a retransmission.

Packets are authenticated and encrypted with AES-128-GCM. The key is
generated by the server and delivered over the existing TLS control
channel, so the fast path is only as exposed as the control channel.
*/
class FastPathServer {
public:
    explicit FastPathServer(int port);
    ~FastPathServer();

    FastPathServer(const FastPathServer&) = delete;
    FastPathServer& operator=(const FastPathServer&) = delete;

    bool is_valid() const { return socket_ != nullptr; }
    int port() const { return port_; }

    bool create_session(std::uint32_t& session_id, std::array<std::uint8_t, 16>& key);
    void remove_session(std::uint32_t session_id);
    bool is_active(std::uint32_t session_id) const;
    bool send_motion(std::uint32_t session_id, std::int32_t x, std::int32_t y,
                     bool relative);

private:
    struct Session {
        std::array<std::uint8_t, 16> key{};
        ArchNetAddress endpoint = nullptr;
        double last_heartbeat = 0.0;
        std::uint32_t last_seq = 0;
        std::uint32_t tx_seq = 0;
        bool has_seq = false;
    };

    void receive_loop();
    void handle_packet(const std::uint8_t* data, std::size_t len, ArchNetAddress from);

    ArchSocket socket_ = nullptr;
    int port_ = 0;
    std::atomic<bool> running_{false};
    Thread* thread_ = nullptr;
    mutable std::mutex mutex_;
    std::map<std::uint32_t, Session> sessions_;
};

//! Client side of the UDP fast path
class FastPathClient {
public:
    FastPathClient(IEventQueue* events, const EventTarget* target,
                   const NetworkAddress& server, int port,
                   std::uint32_t session_id,
                   const std::array<std::uint8_t, 16>& key);
    ~FastPathClient();

    FastPathClient(const FastPathClient&) = delete;
    FastPathClient& operator=(const FastPathClient&) = delete;

    bool is_valid() const { return socket_ != nullptr; }

private:
    void receive_loop();
    void send_heartbeat();
    void handle_packet(const std::uint8_t* data, std::size_t len);

    IEventQueue* events_;
    const EventTarget* target_;
    NetworkAddress server_;
    int port_;
    std::uint32_t session_id_;
    std::array<std::uint8_t, 16> key_;
    ArchSocket socket_ = nullptr;
    std::atomic<bool> running_{false};
    Thread* thread_ = nullptr;
    std::uint32_t seq_ = 0;
    std::uint32_t last_rx_seq_ = 0;
    bool has_rx_seq_ = false;
};

} // namespace inputleap
